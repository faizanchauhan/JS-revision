//switch case

let score = "two";

switch (score) {
    case "zero":
        console.log(`one`);
        break;
    case "one":
        console.log(`two`);
        break;
    case "two":
        console.log(`three`);
        break;
    case "three":
        console.log("four");
        break;

    default:
        console.log(`default case activated`);
        break;
}